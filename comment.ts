import type { AgentResult } from "./graph.js";
import type { ParsedLog } from "./types.js";

/** Finds the 1-based line number of an evidence quote so reviewers can jump to it. */
function lineOf(quote: string, parsed: ParsedLog): number | undefined {
  const q = quote.replace(/\s+/g, " ").trim();
  const i = parsed.lines.findIndex((l) => l.replace(/\s+/g, " ").includes(q));
  return i >= 0 ? i + 1 : undefined;
}

export function toComment(result: AgentResult, parsed: ParsedLog, logUrl?: string): string {
  const link = logUrl ? `\n\n[Full log](${logUrl})` : "";
  if (result.status === "abstained" || !result.diagnosis) {
    return `### CI failure: could not diagnose\n\nThe agent did not find enough evidence in the log to name a cause (${result.reason}). A human should read the first failing step.${link}`;
  }
  const d = result.diagnosis;
  const evidence = d.evidence
    .map((q) => {
      const n = lineOf(q, parsed);
      return `- ${n ? `line ${n}: ` : ""}\`${q.trim()}\``;
    })
    .join("\n");
  return [
    `### CI failure: ${d.category} (confidence ${Math.round(d.confidence * 100)}%)`,
    "",
    d.cause,
    "",
    "**Evidence from the log**",
    evidence,
    "",
    "**Suggested fix**",
    d.suggestedFix,
    "",
    "_Generated by an automated agent. Review before acting._" + link,
  ].join("\n");
}
